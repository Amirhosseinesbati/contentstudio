/* Dedicated, local-only browser QA. No publishing, provider or n8n execution. */
const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const playwright = require(process.env.CONTENTSTUDIO_PLAYWRIGHT || 'playwright')
const root = path.resolve(__dirname, '..')
const base = process.env.CONTENTSTUDIO_PREVIEW_URL || 'http://127.0.0.1:4319'
const output = path.join(root, 'tmp', 'preview', 'theme-qa')
if (!/^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(base)) throw Error('Loopback preview required')
async function main() {
  fs.mkdirSync(output, { recursive: true })
  const browser = await playwright.chromium.launch({ headless: true, executablePath: process.env.CONTENTSTUDIO_BROWSER || 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe' })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, colorScheme: 'light' })
  const page = await context.newPage()
  page.setDefaultTimeout(18000)
  const errors = [], businessRequests = [], sizes = [], screenshots = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('request', (request) => { if (request.url().includes('/api/')) businessRequests.push({ url: request.url(), method: request.method() }) })
  await context.route('**/*', (route) => /^http:\/\/(127\.0\.0\.1|localhost):/.test(route.request().url()) ? route.continue() : route.abort())
  const theme = async (name, scope = page) => { await scope.getByRole('button', { name: `${name} theme`, exact: true }).click(); await page.waitForFunction((value) => document.documentElement.dataset.themePreference === value, name.toLowerCase()) }
  const resolved = () => page.evaluate(() => document.documentElement.dataset.theme)
  const overflow = async (label) => { const excess = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth); assert(excess <= 1, `${label}: overflow ${excess}px`); return excess }
  async function shot(label, fullPage = false) { await page.screenshot({ path: path.join(output, `${label}.png`), fullPage }); screenshots.push(`${label}.png`) }
  async function login(email) {
    await page.getByLabel('Email address').fill(email)
    await page.getByLabel('Password', { exact: true }).fill('DemoStudio!2026')
    await page.getByRole('button', { name: 'Enter workspace' }).click()
    await page.getByRole('navigation', { name: 'Main navigation' }).waitFor()
    await page.locator('.asset-workspace-heading h3').waitFor()
  }
  try {
    await page.goto(base)
    assert.equal(await resolved(), 'dark', 'Fresh visit must default dark on a light OS')
    for (const name of ['Dark', 'Light']) {
      await theme(name)
      await shot(`${name.toLowerCase()}-login-1440`)
      await page.setViewportSize({ width: 390, height: 1000 })
      await overflow(`${name} login 390`)
      await shot(`${name.toLowerCase()}-login-390`, true)
      await page.setViewportSize({ width: 1440, height: 1000 })
    }
    await theme('Dark')
    await login('admin@studio.test')
    const batches = await (await page.request.get(`${base}/api/v1/batches`)).json()
    const mediaReport = JSON.parse(fs.readFileSync(path.join(root, 'tmp/media-checkpoint/report.json'), 'utf8'))
    const batchId = batches.items.some((batch) => batch.id === mediaReport.batch_id) ? mediaReport.batch_id : batches.items[0].id
    await page.getByRole('combobox', { name: 'Select content batch' }).selectOption(batchId)
    await page.locator('.batch-kicker').filter({ hasText: batchId.slice(0, 8).toUpperCase() }).waitFor().catch(() => page.locator('.asset-workspace-heading h3').waitFor())
    await page.locator('.production-path').waitFor()
    await page.locator('.asset-tabs [role=tab]').filter({ hasText: 'Article' }).click()
    await page.locator('.text-preview').waitFor()
    await page.locator('.segment-time').first().click()
    // Obtain the real local recording frame, then pause; do not style/filter media.
    await page.locator('video').first().evaluate(async (video) => {
      video.muted = true
      await Promise.race([video.play().catch(() => {}), new Promise((resolve) => setTimeout(resolve, 5000))])
      video.pause()
    }).catch(() => {})
    const paperColors = () => page.locator('.text-preview').evaluate((element) => { const style = getComputedStyle(element); const title = getComputedStyle(element.querySelector('h4')); return [style.backgroundColor, style.color, title.color, title.fontFamily] })
    const authoredBefore = await paperColors()
    for (const name of ['Dark', 'Light']) {
      await theme(name)
      assert.deepEqual(await paperColors(), authoredBefore, 'Theme must preserve authored paper palette')
      for (const width of [1440, 1024, 768, 390]) {
        await page.setViewportSize({ width, height: 1000 })
        await page.evaluate(() => window.scrollTo(0, 0))
        const excess = await overflow(`${name} studio ${width}`)
        sizes.push({ theme: name.toLowerCase(), width, overflow: excess })
        await shot(`${name.toLowerCase()}-studio-${width}`)
        if (width === 390) { await page.locator('.asset-workspace-heading').scrollIntoViewIfNeeded(); await shot(`${name.toLowerCase()}-review-${width}`) }
      }
    }
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.getByRole('button', { name: 'Edit asset', exact: true }).click()
    const unsaved = 'Unsaved editorial draft — retained through appearance changes.'
    await page.getByLabel('Body text / caption').fill(unsaved)
    await page.evaluate(() => { window.__qaEditor = document.querySelector('#asset-body'); window.__qaSource = document.querySelector('.transcript-segment--selected') })
    const requestCount = businessRequests.length
    await theme('Dark'); await theme('Light'); await theme('System')
    await page.emulateMedia({ colorScheme: 'dark' })
    await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark')
    await page.emulateMedia({ colorScheme: 'light' })
    await page.waitForFunction(() => document.documentElement.dataset.theme === 'light')
    assert.equal(await page.getByLabel('Body text / caption').inputValue(), unsaved)
    assert(await page.evaluate(() => window.__qaEditor === document.querySelector('#asset-body') && window.__qaSource === document.querySelector('.transcript-segment--selected')))
    assert.equal((await page.locator('.asset-tabs button.active').innerText()).replace(/\s+/g, ' '), 'Article 1')
    assert.equal(businessRequests.length, requestCount, 'Appearance must not trigger business requests')
    await theme('Dark')
    await page.emulateMedia({ colorScheme: 'light' })
    assert.equal(await resolved(), 'dark')
    await page.getByRole('button', { name: 'Close editor', exact: true }).click()
    await page.setViewportSize({ width: 390, height: 1000 })
    const opener = page.getByRole('button', { name: 'Open navigation', exact: true })
    await opener.click()
    const dialog = page.getByRole('dialog', { name: 'Workspace navigation' })
    await dialog.waitFor()
    await shot('dark-menu-390')
    await theme('Light', dialog)
    assert(await dialog.isVisible(), 'Theme must retain an open menu')
    await shot('light-menu-390')
    const first = dialog.locator('button').first()
    await first.focus()
    await page.keyboard.press('Shift+Tab')
    assert(await dialog.getByRole('button', { name: 'Sign out', exact: true }).evaluate((element) => element === document.activeElement), 'Menu must trap keyboard focus')
    await page.keyboard.press('Escape')
    assert.equal(await opener.getAttribute('aria-expanded'), 'false')
    assert(await opener.evaluate((element) => element === document.activeElement), 'Menu close must restore focus')
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.getByRole('button', { name: 'Light theme', exact: true }).focus()
    assert.notEqual(await page.getByRole('button', { name: 'Light theme', exact: true }).evaluate((element) => getComputedStyle(element).outlineStyle), 'none')
    await shot('light-keyboard-focus-1440')
    await page.getByRole('button', { name: 'Content board' }).click()
    await page.locator('.board-columns').waitFor()
    await shot('light-board-1440')
    await theme('Dark')
    assert.equal((await page.locator('.nav-item[aria-current=page]').innerText()).replace(/\s+/g, ' '), `Content board ${batches.items.length}`)
    await shot('dark-board-1440')
    await page.getByRole('button', { name: /Source library/ }).click()
    await page.locator('.library-grid').waitFor()
    await page.getByText('Brand profiles and version history', { exact: true }).click()
    await page.getByRole('button', { name: 'Create brand profile', exact: true }).click()
    await page.getByLabel('Brand name', { exact: true }).fill('Unsaved brand concept')
    const accent = await page.getByLabel('Media accent color').inputValue()
    await theme('Light')
    assert.equal(await page.getByLabel('Brand name', { exact: true }).inputValue(), 'Unsaved brand concept')
    assert.equal(await page.getByLabel('Media accent color').inputValue(), accent)
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    await shot('light-library-1440')
    await theme('Dark'); await shot('dark-library-1440')
    await page.route('**/api/v1/sources', (route) => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: 'Synthetic QA source service unavailable' }) }))
    await page.reload()
    await page.getByRole('button', { name: /Source library/ }).click()
    await page.getByText('Synthetic QA source service unavailable', { exact: true }).waitFor()
    await theme('Light')
    await shot('light-error-1440')
    await page.unroute('**/api/v1/sources')
    await page.reload()
    await page.locator('.asset-workspace-heading h3').waitFor()
    assert.equal(await resolved(), 'light', 'Saved theme must survive reload')

    const blockedContext = await browser.newContext({ viewport: { width: 390, height: 1000 } })
    await blockedContext.addInitScript(() => { Object.defineProperty(Storage.prototype, 'getItem', { value() { throw new DOMException('Unavailable', 'SecurityError') } }); Object.defineProperty(Storage.prototype, 'setItem', { value() { throw new DOMException('Unavailable', 'SecurityError') } }) })
    const blocked = await blockedContext.newPage()
    blocked.on('pageerror', (error) => errors.push(error.message))
    await blocked.goto(base)
    assert.equal(await blocked.evaluate(() => document.documentElement.dataset.theme), 'dark')
    await blocked.getByRole('button', { name: 'Light theme', exact: true }).click()
    assert.equal(await blocked.evaluate(() => document.documentElement.dataset.theme), 'light')
    await blocked.getByLabel('Email address').fill('Retained input')
    await blocked.getByRole('button', { name: 'Dark theme', exact: true }).click()
    assert.equal(await blocked.getByLabel('Email address').inputValue(), 'Retained input')
    await blockedContext.close()

    const cspContext = await browser.newContext({ colorScheme: 'dark' })
    await cspContext.addInitScript(() => localStorage.setItem('contentstudio.theme', 'light'))
    const cspPage = await cspContext.newPage()
    const cspErrors = []
    cspPage.on('console', (message) => { if (message.type() === 'error') cspErrors.push(message.text()) })
    await cspPage.route('**/theme-prepaint-test', (route) => route.fulfill({ contentType: 'text/html', headers: { 'Content-Security-Policy': "default-src 'none'; script-src 'self'; style-src 'self'" }, body: '<!doctype html><html data-theme="dark"><head><meta name="theme-color" content="#0b1017"><script src="/theme-init.js"></script><link rel="stylesheet" href="/theme-base.css"></head><body></body></html>' }))
    await cspPage.goto(`${base}/theme-prepaint-test`)
    assert.deepEqual(await cspPage.evaluate(() => [document.documentElement.dataset.theme, getComputedStyle(document.documentElement).backgroundColor, getComputedStyle(document.documentElement).colorScheme]), ['light', 'rgb(241, 244, 248)', 'light'])
    assert.deepEqual(cspErrors, [])
    await cspContext.close()
    assert.deepEqual(errors, [])
    assert.equal(businessRequests.some((request) => request.method === 'POST' && !request.url.endsWith('/auth/login')), false, 'QA must not trigger mutations beyond local authentication')
    const report = { label: 'Local synthetic appearance and state-retention QA', base, checks: { fresh_dark: true, saved_theme: true, system_live: true, explicit_ignores_os: true, blocked_storage: true, csp_prepaint: true, editor_dom_and_draft_retained: true, source_selection_and_filter_retained: true, brand_draft_and_media_accent_retained: true, no_business_requests_from_theme: true, authored_paper_palette_unchanged: true, mobile_menu_focus_and_escape: true, route_retained: true, error_state: true }, sizes, screenshots, page_errors: errors, csp_errors: cspErrors, external_workflows_executed: false }
    fs.writeFileSync(path.join(output, 'theme-rollout.json'), JSON.stringify(report, null, 2))
    console.log(JSON.stringify(report, null, 2))
  } catch (error) { await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true }); throw error }
  finally { await browser.close() }
}
main().catch((error) => { console.error(error); process.exitCode = 1 })
